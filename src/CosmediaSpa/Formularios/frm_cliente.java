    private boolean validarCampos() {
        String cedula = txt_cedula.getText().trim();
        String nombre = txt_nombre.getText().trim();
        String direccion = txt_direccion.getText().trim();
        String telefono = txt_telefono.getText().trim();
        String email = txt_email.getText().trim();
        Date fechaReg = cb_fechaderegistro.getDate();

        Cliente cli = new Cliente(cedula, nombre, direccion, telefono, email, fechaReg);
        if (!cli.validarDatos()) {
            JOptionPane.showMessageDialog(this,
                    "Por favor ingrese datos válidos en todos los campos (cédula, email y teléfono).",
                    "Error de validación", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

