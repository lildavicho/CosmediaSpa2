    private void btn_agregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_agregarActionPerformed
      if (!validarCampos()) return;

    String cedula    = txt_cedula.getText().trim();
    String nombre    = txt_nombre.getText().trim();
    String direccion = txt_direccion.getText().trim();
    String telefono  = txt_telefono.getText().trim();
    String email     = txt_email.getText().trim();
    Date   fecha     = cb_fechaderegistro.getDate();

    Cliente cli = new Cliente(cedula, nombre, direccion, telefono, email, fecha);

    // 1) Creamos el JFileChooser y lo configuramos:
    JFileChooser chooser = new JFileChooser();
    chooser.setDialogTitle("Guardar Cliente (.txt)");
    chooser.setSelectedFile(new File("cliente_" + cedula + ".txt"));
    chooser.setFileFilter(
        new FileNameExtensionFilter("Archivos de texto (*.txt)", "txt")
    );

    // 2) Lo inyectamos en el cliente:
    cli.setFileChooser(chooser);

    // 3) Llamamos a su mtd_guardar() (ya no pide parámetros):
    if (!cli.mtd_guardar()) {
        // canceló o error
        return;
    }

    // 4) Verificamos duplicados en la tabla:
    if (Cliente.existeRegistro(modeloTabla, cedula)) {
        JOptionPane.showMessageDialog(this,
            "Ya existe un cliente con esa cédula en la tabla.",
            "Duplicado", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 5) Insertamos la fila, usando TU sdf para la fecha:
    modeloTabla.addRow(new Object[]{
        cli.getCedula(),
        cli.getNombre(),
        cli.getDireccion(),
        cli.getTelefono(),
        cli.getEmail(),
        sdf.format(cli.getFechaRegistro())
    });

    JOptionPane.showMessageDialog(this,
        "Cliente guardado en archivo y tabla.",
        "Éxito", JOptionPane.INFORMATION_MESSAGE);
    limpiarCampos();
    }//GEN-LAST:event_btn_agregarActionPerformed

    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
        if (!editMode) {
        // Entrar en modo edición
        int fila = tabla_clientes.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this,
                "Seleccione una fila para editar.",
                "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Volcar valores a los campos
        txt_cedula.setText(modeloTabla.getValueAt(fila, 0).toString());
        txt_nombre.setText(modeloTabla.getValueAt(fila, 1).toString());
        txt_direccion.setText(modeloTabla.getValueAt(fila, 2).toString());
        txt_telefono.setText(modeloTabla.getValueAt(fila, 3).toString());
        txt_email.setText(modeloTabla.getValueAt(fila, 4).toString());
        try {
            Date fecha = sdf.parse(modeloTabla.getValueAt(fila, 5).toString());
            cb_fechaderegistro.setDate(fecha);
        } catch (ParseException ex) {
            cb_fechaderegistro.setDate(new Date());
        }
        // Activar modo edición
        editMode = true;
        editRow  = fila;
        btn_editar.setText("GUARDAR");
        btn_agregar.setEnabled(false);
        btn_eliminar.setEnabled(false);
        btn_buscar .setEnabled(false);
    } else {
        // --- Guardar cambios ---
        if (!validarCampos()) return;

        String cedula    = txt_cedula.getText().trim();
        String nombre    = txt_nombre.getText().trim();
        String direccion = txt_direccion.getText().trim();
        String telefono  = txt_telefono.getText().trim();
        String email     = txt_email.getText().trim();
        Date   fecha     = cb_fechaderegistro.getDate();

        // Recreamos el objeto Cliente con los nuevos datos
        Cliente cli = new Cliente(cedula, nombre, direccion, telefono, email, fecha);

        // Inyectamos un JFileChooser configurado para guardar
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Guardar Cliente (.txt)");
        chooser.setSelectedFile(new File("cliente_" + cedula + ".txt"));
        chooser.setFileFilter(new FileNameExtensionFilter("Archivos de texto (*.txt)", "txt"));
        cli.setFileChooser(chooser);

        // Llamamos al mtd_guardar() sin parámetros
        if (!cli.mtd_guardar()) {
            JOptionPane.showMessageDialog(this,
                "Error al actualizar archivo de cliente.",
                "Error I/O", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Actualizamos la fila en la tabla
        modeloTabla.setValueAt(cedula,   editRow, 0);
        modeloTabla.setValueAt(nombre,   editRow, 1);
        modeloTabla.setValueAt(direccion,editRow, 2);
        modeloTabla.setValueAt(telefono, editRow, 3);
        modeloTabla.setValueAt(email,    editRow, 4);
        modeloTabla.setValueAt(sdf.format(fecha), editRow, 5);

        JOptionPane.showMessageDialog(this,
            "Cliente actualizado en archivo y tabla.",
            "Éxito", JOptionPane.INFORMATION_MESSAGE);

        // Salimos de modo edición
        limpiarCampos();
    }
    }//GEN-LAST:event_btn_editarActionPerformed

    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        int fila = tabla_clientes.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione una fila de la tabla para eliminar.",
                    "Atención",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // 1) Obtener la cédula de la fila seleccionada
        String cedula = modeloTabla.getValueAt(fila, 0).toString();

        // 2) Eliminar el archivo físico
        Cliente cli = new Cliente();
        cli.setCedula(cedula);
        boolean okArchivo = cli.mtd_eliminar();

        if (okArchivo) {
            // 3) Remover la fila de la tabla
            modeloTabla.removeRow(fila);

            // 4) Limpiar selección y campos del formulario
            tabla_clientes.clearSelection();
            txt_cedula.setText("");
            txt_nombre.setText("");
            txt_direccion.setText("");
            txt_telefono.setText("");
            txt_email.setText("");
            cb_fechaderegistro.setDate(new Date());

            JOptionPane.showMessageDialog(
                    this,
                    "Cliente eliminado de archivo y tabla.",
                    "Éxito",
                    JOptionPane.INFORMATION_MESSAGE
            );
        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo eliminar el cliente (archivo no encontrado).",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed

    private void btn_buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscarActionPerformed
       if (editMode) {
            JOptionPane.showMessageDialog(this,
                "No puede buscar mientras edita.",
                "Atención",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Limpiar formulario
        limpiarCampos();

        // Abrir diálogo y cargar datos en el objeto
        Cliente cli = new Cliente();
        boolean ok = cli.mtd_buscar();
        if (!ok) {
            JOptionPane.showMessageDialog(this,
                "No se cargó ningún cliente o se canceló la selección.",
                "Información",
                JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        String cedula    = cli.getCedula();
        txt_cedula.setText(cedula);
        txt_nombre.setText(cli.getNombre());
        txt_direccion.setText(cli.getDireccion());
        txt_telefono.setText(cli.getTelefono());
        txt_email.setText(cli.getEmail());
        cb_fechaderegistro.setDate(cli.getFechaRegistro());

        // ←←← Chequeo duplicado:
        if (Cliente.existeRegistro(modeloTabla, cedula)) {
            // sólo selecciono la fila existente
            for (int i = 0; i < modeloTabla.getRowCount(); i++) {
                if (modeloTabla.getValueAt(i, 0).equals(cedula)) {
                    tabla_clientes.setRowSelectionInterval(i, i);
                    break;
                }
            }
            return;
        }

        // si no existía, la agrego
        modeloTabla.addRow(new Object[]{
            cedula,
            cli.getNombre(),
            cli.getDireccion(),
            cli.getTelefono(),
            cli.getEmail(),
            sdf.format(cli.getFechaRegistro())
        });
        int nuevaFila = modeloTabla.getRowCount() - 1;
        tabla_clientes.setRowSelectionInterval(nuevaFila, nuevaFila);
    }//GEN-LAST:event_btn_buscarActionPerformed

    public static boolean existeRegistro(javax.swing.table.DefaultTableModel model, String cedula) {
    for (int i = 0; i < model.getRowCount(); i++) {
        if (model.getValueAt(i, 0).equals(cedula)) {
            return true;
        }
    }
    return false;
}

