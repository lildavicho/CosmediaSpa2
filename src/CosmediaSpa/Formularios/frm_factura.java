    private List<DetalleFactura> leerDetallesFactura() {
        List<DetalleFactura> lista = new ArrayList<>();
        // Asumo que tu DefaultTableModel de detalle factura está en la variable modeloDetFactura
        for (int i = 0; i < modeloDetFactura.getRowCount(); i++) {
            String codigo = modeloDetFactura.getValueAt(i, 0).toString();
            String descripcion = modeloDetFactura.getValueAt(i, 1).toString();
            int cantidad = Integer.parseInt(modeloDetFactura.getValueAt(i, 2).toString());
            double precio = Double.parseDouble(modeloDetFactura.getValueAt(i, 3).toString());
            // El constructor de DetalleFactura recibe (código, desc, cantidad, precioUnitario)
            lista.add(new DetalleFactura(codigo, descripcion, cantidad, precio));
        }
        return lista;
    }

    private void recalcular() {
        double subtotal = 0;

        // 1) Sumar precios de consulta (columna 3)
        for (int i = 0; i < modeloConsulta.getRowCount(); i++) {
            Object val = modeloConsulta.getValueAt(i, 3);
            subtotal += (val instanceof Number)
                    ? ((Number) val).doubleValue()
                    : Double.parseDouble(val.toString());
        }

        // 2) Sumar totales de tratamiento (columna 4)
        for (int i = 0; i < modeloTratamiento.getRowCount(); i++) {
            Object val = modeloTratamiento.getValueAt(i, 4);
            subtotal += (val instanceof Number)
                    ? ((Number) val).doubleValue()
                    : Double.parseDouble(val.toString());
        }

        // Mostrar subtotal
        txt_subtotal.setText(String.format("%.2f", subtotal));

        // 3) Descuento
        int descPct = Integer.parseInt(cmb_descuento.getSelectedItem().toString());
        double montoDesc = subtotal * descPct / 100.0;
        txt_descuento.setText(String.format("%.2f", montoDesc));

        // 4) Base y IVA fijo al 15%
        double base = subtotal - montoDesc;
        double ivaPct = 15.0;
        txt_iva.setText(String.format("%.0f", ivaPct));         // campo de IVA%
        double montoIva = base * ivaPct / 100.0;
        txt_montoiva.setText(String.format("%.2f", montoIva));

        // 5) Total final
        double total = base + montoIva;
        txt_total.setText(String.format("%.2f", total));
    }

    private void actualizarMontos() {
        double subtotal = 0;
        try {
            subtotal = Double.parseDouble(txt_subtotal.getText().trim());
        } catch (NumberFormatException e) {
            // si no es número, lo tomamos como 0
        }

        // % de descuento seleccionado
        double descPct = 0;
        try {
            descPct = Double.parseDouble(cmb_descuento.getSelectedItem().toString());
        } catch (Exception e) {
        }

        double montoDesc = subtotal * descPct / 100.0;
        double base = subtotal - montoDesc;

        // IVA fijo 15%
        double ivaPct = 15.0;
        double montoIva = base * ivaPct / 100.0;
        double total = base + montoIva;

        // actualizar campos
        txt_descuento.setText(String.format("%.2f", montoDesc));
        txt_iva.setText(String.format("%.0f", ivaPct));    // muestra "15"
        txt_montoiva.setText(String.format("%.2f", montoIva));
        txt_total.setText(String.format("%.2f", total));
    }

    private boolean validarFactura() {
        if (txt_numerofactura.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Número de factura vacío.", "Error", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        if (tabla_cliente.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un cliente.", "Error", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        if (modeloDetFactura.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No hay detalle de factura.", "Error", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

    private Cliente leerClienteSeleccionado() {
        int f = tabla_cliente.getSelectedRow();
        String ced = modeloCliente.getValueAt(f, 0).toString();
        Cliente cli = new Cliente();
        cli.setCedula(ced);
        cli.mtd_buscar();
        return cli;
    }

    private boolean existeRegistro(DefaultTableModel model, String clave) {
        for (int i = 0; i < model.getRowCount(); i++) {
            if (model.getValueAt(i, 0).equals(clave)) {
                return true;
            }
        }
        return false;
    }


