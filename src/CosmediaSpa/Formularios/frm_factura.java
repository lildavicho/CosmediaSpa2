    private void btn_buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscarActionPerformed
        if (editMode) {
            JOptionPane.showMessageDialog(this,
                    "Termine la edición antes de buscar.",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        limpiarFactura();

        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Buscar Factura (.txt)");
        chooser.setFileFilter(new FileNameExtensionFilter("Archivos de texto (*.txt)", "txt"));
        if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }
        File file = chooser.getSelectedFile();
        String name = file.getName();
        // Extraer número de factura de “factura_XXX.txt”
        String prefix = "factura_";
        String suffix = ".txt";
        String numFac;
        if (name.startsWith(prefix) && name.endsWith(suffix)) {
            numFac = name.substring(prefix.length(), name.length() - suffix.length());
        } else {
            numFac = name.replaceFirst("\\.txt$", "");
        }
        txt_numerofactura.setText(numFac);

        // Leer el contenido
        Factura f = new Factura();
        f.setNumeroFactura(numFac);
        if (!f.mtd_buscar()) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró o no se pudo leer la factura.",
                    "Error I/O",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Cargo Cliente
        Cliente cli = new Cliente();
        cli.setCedula(f.getCliente().getCedula());
        cli.mtd_buscar();
        modeloCliente.addRow(new Object[]{
            cli.getCedula(),
            cli.getNombre(),
            cli.getDireccion(),
            cli.getTelefono(),
            cli.getEmail(),
            sdf.format(cli.getFechaRegistro())
        });

        // Cargo DetalleFactura
        for (DetalleFactura d : f.getDetalles()) {
            modeloDetFactura.addRow(new Object[]{
                d.getCodigoServicio(),
                d.getDescripcionServicio(),
                d.getCantidadSesiones(),
                d.getPrecioUnitario(),
                d.getTotalLinea()
            });
        }

        // Totales
        cb_fecha.setDate(f.getFecha());
        txt_subtotal.setText(String.valueOf(f.getSubtotal()));
        cmb_descuento.setSelectedItem(String.valueOf(f.getDescuentoPct()));
        txt_descuento.setText(String.valueOf(f.getMontoDescuento()));
        txt_iva.setText(String.valueOf(f.getIvaPct()));
        txt_montoiva.setText(String.valueOf(f.getMontoIva()));
        txt_total.setText(String.valueOf(f.getTotal()));

        // Y añado una fila en la tabla de factura históricas
        modeloFactura.addRow(new Object[]{
            f.getNumeroFactura(),
            sdf.format(f.getFecha()),
            cli.getCedula() + "-" + cli.getNombre(),
            f.getSubtotal(),
            f.getDescuentoPct(),
            f.getIvaPct(),
            f.getMontoIva(),
            f.getTotal()
        });
        int fila = modeloFactura.getRowCount() - 1;
        tabla_factura.setRowSelectionInterval(fila, fila);
    }//GEN-LAST:event_btn_buscarActionPerformed

