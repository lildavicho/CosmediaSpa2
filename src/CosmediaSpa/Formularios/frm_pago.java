    private void btn_agregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_agregarActionPerformed
        if (!validarFormulario()) return;

    Pago p = new Pago(
        txt_codigos.getText().trim(),
        txt_numFacturas.getText().trim(),
        cb_fechapagos.getDate(),
        cmb_metodoPago.getSelectedItem().toString(),
        cmb_estadoPago.getSelectedItem().toString(),
        txt_observaciones.getText().trim(),
        Double.parseDouble(txt_monto.getText().trim().replace(",","."))
    );

    JFileChooser chooser = new JFileChooser();
    chooser.setDialogTitle("Guardar Pago (.txt)");
    chooser.setSelectedFile(new File("pago_" + p.getCodigoPago() + ".txt"));
    chooser.setFileFilter(new FileNameExtensionFilter("Archivos de texto (*.txt)", "txt"));
    if (chooser.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) return;

    File archivo = chooser.getSelectedFile();
    if (!archivo.getName().toLowerCase().endsWith(".txt"))
        archivo = new File(archivo.getAbsolutePath()+".txt");

    p.setArchivo(archivo);
    if (!p.mtd_guardar()) return;

    // **Solo ahora** añadimos la fila a la tabla
    modeloPago.addRow(new Object[]{
        p.getCodigoPago(),
        p.getNumeroFactura(),
        sdfPago.format(p.getFechaPago()),
        p.getMetodoPago(),
        p.getEstado(),
        p.getObservaciones(),
        String.format(Locale.US, "%.2f", p.getMonto())
    });

    JOptionPane.showMessageDialog(this,
        "Pago guardado correctamente en archivo y tabla.",
        "Éxito", JOptionPane.INFORMATION_MESSAGE);
    limpiarCampos();
    }

