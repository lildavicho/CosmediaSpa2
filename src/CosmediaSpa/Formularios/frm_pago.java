    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
       if (!editMode) {
        // si no está en edición, delega a buscar
        btn_buscar1ActionPerformed(evt);
        return;
    }
    if (!validarFormulario()) return;

    Pago p = new Pago(
        txt_codigos.getText().trim(),
        txt_numFacturas.getText().trim(),
        cb_fechapagos.getDate(),
        cmb_metodoPago.getSelectedItem().toString(),
        cmb_estadoPago.getSelectedItem().toString(),
        txt_observaciones.getText().trim(),
        Double.parseDouble(txt_monto.getText().trim().replace(",","."))
    );

    p.setArchivo(archivoEditando);
    if (!p.mtd_guardar()) return;

    // refrescamos la fila editada
    modeloPago.setValueAt(p.getCodigoPago(),               editRow,0);
    modeloPago.setValueAt(p.getNumeroFactura(),            editRow,1);
    modeloPago.setValueAt(sdfPago.format(p.getFechaPago()),editRow,2);
    modeloPago.setValueAt(p.getMetodoPago(),               editRow,3);
    modeloPago.setValueAt(p.getEstado(),                   editRow,4);
    modeloPago.setValueAt(p.getObservaciones(),            editRow,5);
    modeloPago.setValueAt(String.format(Locale.US,"%.2f",p.getMonto()), editRow,6);

    JOptionPane.showMessageDialog(this,
        "Pago actualizado correctamente.",
        "Éxito", JOptionPane.INFORMATION_MESSAGE);
    limpiarCampos();
    }//GEN-LAST:event_btn_editarActionPerformed

    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
       if (editMode) {
        JOptionPane.showMessageDialog(this,
            "No puede eliminar mientras edita.",
            "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }
    int fila = tabla_pagos.getSelectedRow();
    if (fila<0) {
        JOptionPane.showMessageDialog(this,
            "Seleccione un pago para eliminar.",
            "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }

    JFileChooser chooser = new JFileChooser();
    chooser.setDialogTitle("Eliminar Pago (.txt)");
    chooser.setFileFilter(new FileNameExtensionFilter("Archivos de texto (*.txt)", "txt"));
    if (chooser.showOpenDialog(this)!=JFileChooser.APPROVE_OPTION) return;

    File archivo = chooser.getSelectedFile();
    Pago p = new Pago();
    p.setArchivo(archivo);
    if (!p.mtd_eliminar()) return;

    modeloPago.removeRow(fila);
    JOptionPane.showMessageDialog(this,
        "Pago eliminado de disco y de la tabla.",
        "Éxito", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btn_eliminarActionPerformed

    private void btn_buscar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscar1ActionPerformed
        // 1) Si ya estás editando, no permitimos otro buscar
    if (editMode) {
        JOptionPane.showMessageDialog(this,
            "Ya está en modo edición. Termine o cancele antes de buscar otro pago.",
            "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2) Abrir JFileChooser para que el usuario elija dónde está el .txt de pago
    JFileChooser chooser = new JFileChooser();
    chooser.setDialogTitle("Abrir Pago (.txt)");
    chooser.setFileFilter(new FileNameExtensionFilter("Archivos de texto (*.txt)", "txt"));
    if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
        return; // el usuario canceló
    }
    File archivo = chooser.getSelectedFile();
    if (!archivo.exists()) {
        JOptionPane.showMessageDialog(this,
            "El archivo no existe:\n" + archivo.getAbsolutePath(),
            "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 3) Cargar el pago desde el archivo elegido
    Pago p = new Pago();
    p.setArchivo(archivo);
    if (!p.mtd_buscar()) {
        // mtd_buscar ya mostró el error correspondiente
        return;
    }

    // 4) Volcar datos al formulario
    txt_codigos.setText(p.getCodigoPago());
    txt_numFacturas.setText(p.getNumeroFactura());
    cb_fechapagos.setDate(p.getFechaPago());
    cmb_metodoPago.setSelectedItem(p.getMetodoPago());
    cmb_estadoPago.setSelectedItem(p.getEstado());
    txt_observaciones.setText(p.getObservaciones());
    txt_monto.setText(String.format(Locale.US, "%.2f", p.getMonto()));

    // 5) Refrescar la tabla de pagos con **solo** este registro (o coméntalo si prefieres append)
    modeloPago.setRowCount(0);
    modeloPago.addRow(new Object[]{
        p.getCodigoPago(),
        p.getNumeroFactura(),
        sdfPago.format(p.getFechaPago()),
        p.getMetodoPago(),
        p.getEstado(),
        p.getObservaciones(),
        String.format(Locale.US, "%.2f", p.getMonto())
    });

    // 6) Preparar para editar este pago
    archivoEditando = archivo;
    editMode        = true;
    editRow         = modeloPago.getRowCount() - 1;  // fíjate la fila recién añadida
    tabla_pagos.setRowSelectionInterval(editRow, editRow);

    // 7) Ajustar botones
    btn_editar.setText("Guardar");
    btn_agregar.setEnabled(false);
    btn_eliminar.setEnabled(false);
    }//GEN-LAST:event_btn_buscar1ActionPerformed

    private void limpiarCampos() {
        txt_codigos.setText("");
        txt_numFacturas.setText("");
        cb_fechapagos.setDate(new Date());
        cmb_metodoPago.setSelectedIndex(0);
        cmb_estadoPago.setSelectedIndex(0);
        txt_observaciones.setText("");
        txt_monto.setText("");
        editMode = false;
        editRow = -1;
        btn_editar.setText("EDITAR");
        btn_agregar.setEnabled(true);
        btn_eliminar.setEnabled(true);
        btn_buscarFact.setEnabled(true);
    }

    private boolean validarFormulario() {
        String textoMonto = txt_monto.getText().trim().replace(",", ".");
        try {
            double m = Double.parseDouble(textoMonto);
            if (m < 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Monto inválido.",
                    "Validación", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

