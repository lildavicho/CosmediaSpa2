    private void btn_buscarFactActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscarFactActionPerformed
        if (editMode) {
            JOptionPane.showMessageDialog(this,
                    "No puede buscar factura mientras edita un pago.",
                    "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 1) Una sola vez abrimos el chooser
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Abrir Factura (.txt)");
        chooser.setFileFilter(new FileNameExtensionFilter("Texto (*.txt)", "txt"));
        if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return; // canceló
        }
        File fichero = chooser.getSelectedFile();

        // 2) Cargar factura desde archivo
        Factura f = new Factura();
        if (!f.cargarDesdeArchivo(fichero)) {

            return; // error interno ya mostrado
        }

        // 3) Preparar texto de cliente
        Cliente cli = f.getCliente();
        String clienteTexto;
        if (cli != null && cli.getCedula() != null && !cli.getCedula().isEmpty()) {
            clienteTexto = cli.getCedula()
                    + (cli.getNombre() != null && !cli.getNombre().isEmpty()
                    ? " – " + cli.getNombre()
                    : "");
        } else {
            clienteTexto = "Cliente no encontrado";
        }

        // 4) Rellenar tabla y formulario
        modeloFactura.setRowCount(0);
        modeloFactura.addRow(new Object[]{
            f.getNumeroFactura(),
            sdfFactura.format(f.getFecha()),
            clienteTexto,
            f.getDetalles().size(), // consultas
            f.getDetalles().size(), // detalleFactura
            f.getDetalles().size(), // tratamientos (ajusta si cambias)
            String.format(Locale.US, "%.2f", f.getSubtotal()),
            String.format(Locale.US, "%.2f", f.getDescuentoPct()),
            String.format(Locale.US, "%.2f", f.getMontoDescuento()),
            String.format(Locale.US, "%.2f", f.getIvaPct()),
            String.format(Locale.US, "%.2f", f.getMontoIva()),
            String.format(Locale.US, "%.2f", f.getTotal())
        });

        txt_numFacturas.setText(f.getNumeroFactura());
        cb_fechapagos.setDate(f.getFecha());
        txt_monto.setText(String.format(Locale.US, "%.2f", f.getTotal()));
    }//GEN-LAST:event_btn_buscarFactActionPerformed

