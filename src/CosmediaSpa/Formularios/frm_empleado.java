    private void limpiarCampos() {
    txt_cedula.setText("");
    txt_nombre.setText("");
    txt_telefono.setText("");
    txt_email.setText("");
    cb_fechadecontratacion.setDate(null);
    tabla_empleado.clearSelection();
}
    
    private Empleado leerEmpleadoDesdeCampos() {
    // El date-picker ya devuelve un Date
    Date fecha = cb_fechadecontratacion.getDate();
    return new Empleado(
        txt_cedula.getText().trim(),
        txt_nombre.getText().trim(),
        txt_telefono.getText().trim(),
        txt_email.getText().trim(),
        fecha
    );
}
    
    private boolean validarCampos() {
         String ced = txt_cedula.getText().trim();
    if (!ced.matches("\\d{10}") || !new Empleado().validarCedula(ced)) {
        JOptionPane.showMessageDialog(this, "Ingrese una cédula válida (10 dígitos).");
        return false;
    }
    String nom = txt_nombre.getText().trim();
    if (nom.isEmpty()) {
        JOptionPane.showMessageDialog(this, "El nombre no puede estar vacío.");
        return false;
    }
    String tel = txt_telefono.getText().trim();
    if (!tel.matches("\\d{7,10}") || !new Empleado().validarTelefono(tel)) {
        JOptionPane.showMessageDialog(this, "Teléfono inválido.");
        return false;
    }
    String mail = txt_email.getText().trim();
    if (!new Empleado().validarEmail(mail)) {
        JOptionPane.showMessageDialog(this, "Email inválido.");
        return false;
    }
    Date fc = cb_fechadecontratacion.getDate();
    if (fc == null) {
        JOptionPane.showMessageDialog(this, "Seleccione la fecha de contratación.");
        return false;
    }
    return true;
    }

    private void volcarTablaAFuentes(int fila) {
        txt_cedula.setText(   modeloTabla.getValueAt(fila, 0).toString());
    txt_nombre.setText(   modeloTabla.getValueAt(fila, 1).toString());
    txt_telefono.setText( modeloTabla.getValueAt(fila, 2).toString());
    txt_email.setText(    modeloTabla.getValueAt(fila, 3).toString());
    // Parsear la cadena de la tabla al date-picker
    try {
        Date d = sdf.parse(modeloTabla.getValueAt(fila, 4).toString());
        cb_fechadecontratacion.setDate(d);
    } catch (ParseException ex) {
        cb_fechadecontratacion.setDate(null);
    }
    }
