    private void btn_agregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_agregarActionPerformed
      if (editMode) {
        JOptionPane.showMessageDialog(this, "Termine la edición antes de agregar otro.");
        return;
    }
    if (!validarCampos()) return;

    Empleado emp = leerEmpleadoDesdeCampos();
    if (!emp.mtd_guardar()) {
        JOptionPane.showMessageDialog(this,
            "Error al guardar archivo de empleado.",
            "Error I/O",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    if (existeRegistro(emp.getCedula())) {
        JOptionPane.showMessageDialog(this,
            "El empleado ya está en la tabla.",
            "Aviso",
            JOptionPane.INFORMATION_MESSAGE
        );
        limpiarCampos();
        return;
    }

    modeloTabla.addRow(new Object[]{
        emp.getCedula(),
        emp.getNombre(),
        emp.getTelefono(),
        emp.getEmail(),
        sdf.format(emp.getFechaContratacion())
    });
    JOptionPane.showMessageDialog(this,
        "Empleado guardado en archivo y tabla.",
        "Éxito",
        JOptionPane.INFORMATION_MESSAGE
    );
    limpiarCampos();
    }//GEN-LAST:event_btn_agregarActionPerformed

    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
     if (!editMode) {
        int fila = tabla_empleado.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this,
                "Seleccione una fila para editar.",
                "Aviso",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        volcarTablaAFuentes(fila);
        editMode = true;
        editRow  = fila;
        btn_editar.setText("GUARDAR");
        btn_agregar.setEnabled(false);
        btn_eliminar.setEnabled(false);
        btn_buscar.setEnabled(false);
    } else {
        if (!validarCampos()) return;
        Empleado emp = leerEmpleadoDesdeCampos();
        if (!emp.mtd_guardar()) {
            JOptionPane.showMessageDialog(this,
                "Error al actualizar archivo.",
                "Error I/O",
                JOptionPane.ERROR_MESSAGE
            );
            return;
        }
        // actualizamos fila
        modeloTabla.setValueAt(emp.getCedula(), editRow, 0);
        modeloTabla.setValueAt(emp.getNombre(), editRow, 1);
        modeloTabla.setValueAt(emp.getTelefono(), editRow, 2);
        modeloTabla.setValueAt(emp.getEmail(), editRow, 3);
        modeloTabla.setValueAt(sdf.format(emp.getFechaContratacion()), editRow, 4);

        JOptionPane.showMessageDialog(this,
            "Empleado actualizado en archivo y tabla.",
            "Éxito",
            JOptionPane.INFORMATION_MESSAGE
        );
        // salimos de modo edición
        editMode = false;
        editRow  = -1;
        btn_editar.setText("EDITAR");
        btn_agregar.setEnabled(true);
        btn_eliminar.setEnabled(true);
        btn_buscar.setEnabled(true);
        limpiarCampos();
    }
    }//GEN-LAST:event_btn_editarActionPerformed

    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
  if (editMode) {
        JOptionPane.showMessageDialog(this,
            "No puede eliminar mientras edita.",
            "Aviso",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }
    int fila = tabla_empleado.getSelectedRow();
    if (fila < 0) {
        JOptionPane.showMessageDialog(this,
            "Seleccione una fila para eliminar.",
            "Aviso",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }
    String ced = modeloTabla.getValueAt(fila, 0).toString();
    Empleado emp = new Empleado();
    emp.setCedula(ced);
    if (!emp.mtd_eliminar()) {
        JOptionPane.showMessageDialog(this,
            "No se pudo eliminar archivo de empleado.",
            "Error I/O",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }
    modeloTabla.removeRow(fila);
    limpiarCampos();
    JOptionPane.showMessageDialog(this,
        "Empleado eliminado de archivo y tabla.",
        "Éxito",
        JOptionPane.INFORMATION_MESSAGE
    );
    }//GEN-LAST:event_btn_eliminarActionPerformed

    private void btn_buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscarActionPerformed
       if (editMode) {
        JOptionPane.showMessageDialog(this,
            "No puede buscar mientras edita.",
            "Aviso",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }
    limpiarCampos();
    Empleado emp = new Empleado();
    if (!emp.mtd_buscar()) {
        JOptionPane.showMessageDialog(this,
            "No se cargó ningún empleado o se canceló.",
            "Información",
            JOptionPane.INFORMATION_MESSAGE
        );
        return;
    }
   txt_cedula.setText(emp.getCedula());
txt_nombre.setText(emp.getNombre());
txt_telefono.setText(emp.getTelefono());
txt_email.setText(emp.getEmail());
// Poner la fecha en el JXDatePicker:
cb_fechadecontratacion.setDate(emp.getFechaContratacion());

    if (existeRegistro(emp.getCedula())) {
        for (int i = 0; i < modeloTabla.getRowCount(); i++) {
            if (modeloTabla.getValueAt(i, 0).equals(emp.getCedula())) {
                tabla_empleado.setRowSelectionInterval(i, i);
                break;
            }
        }
    } else {
        modeloTabla.addRow(new Object[]{
            emp.getCedula(),
            emp.getNombre(),
            emp.getTelefono(),
            emp.getEmail(),
            sdf.format(emp.getFechaContratacion())
        });
        int nf = modeloTabla.getRowCount() - 1;
        tabla_empleado.setRowSelectionInterval(nf, nf);
    }
     editMode = true;
    for (int i = 0; i < modeloTabla.getRowCount(); i++) {
        if (modeloTabla.getValueAt(i, 0).equals(emp.getCedula())) {
            editRow = i;
            break;
        }
    }
    btn_editar.setText("GUARDAR");
    }//GEN-LAST:event_btn_buscarActionPerformed

    private boolean existeRegistro(String cedula) {
    for (int i = 0; i < modeloTabla.getRowCount(); i++) {
        if (modeloTabla.getValueAt(i, 0).equals(cedula)) {
            return true;
        }
    }
    return false;
}
    
